package pt.ua.tqs.ecodelivery.reservation;

import java.math.BigDecimal;
import java.time.Clock;
import java.time.Duration;
import java.time.LocalDateTime;
import java.time.ZoneOffset;

import org.springframework.test.util.ReflectionTestUtils;

import pt.ua.tqs.ecodelivery.model.Bike;
import pt.ua.tqs.ecodelivery.model.BikeStatus;
import pt.ua.tqs.ecodelivery.model.Company;
import pt.ua.tqs.ecodelivery.model.Courier;
import pt.ua.tqs.ecodelivery.model.Hub;
import pt.ua.tqs.ecodelivery.model.Payment;
import pt.ua.tqs.ecodelivery.model.PaymentStatus;
import pt.ua.tqs.ecodelivery.model.PaymentType;
import pt.ua.tqs.ecodelivery.model.Reservation;
import pt.ua.tqs.ecodelivery.model.ReservationStatus;
import pt.ua.tqs.ecodelivery.policy.PolicyService;

/**
 * Test data shared by the US 10 (vehicle usage start) tests.
 *
 * <p>Entities are plain objects: their ids are set with {@link ReflectionTestUtils} because the
 * entities have no {@code setId} (ids are generated by the database).
 */
final class StartFixtures {

    /** "Now" in every test: Monday 23 Nov 2026, 10:00 (UTC). */
    static final LocalDateTime NOW = LocalDateTime.of(2026, 11, 23, 10, 0);

    /** Policy values, as configured by the institutional client (deliberately not the defaults). */
    static final int MIN_BATTERY = 20;
    static final Duration MAX_DURATION = Duration.ofHours(6);
    static final BigDecimal DEPOSIT = new BigDecimal("10.00");
    static final BigDecimal NO_DEPOSIT = BigDecimal.ZERO;
    static final int MAX_ACTIVE_PER_COURIER = 1;
    static final Duration START_WINDOW = Duration.ofMinutes(15);

    static final Long HUB_ID = 1L;
    static final Long COURIER_ID = 10L;
    static final Long OTHER_COURIER_ID = 11L;
    static final Long BIKE_ID = 100L;
    static final Long RESERVATION_ID = 1000L;

    private StartFixtures() {
    }

    static Clock clockAt(LocalDateTime now) {
        return Clock.fixed(now.toInstant(ZoneOffset.UTC), ZoneOffset.UTC);
    }

    static PolicyService policy(BigDecimal deposit) {
        return new PolicyService(MIN_BATTERY, MAX_DURATION, deposit, new BigDecimal("0.10"),
                MAX_ACTIVE_PER_COURIER, START_WINDOW);
    }

    static Company company() {
        Company company = new Company();
        company.setName("Rapid Parcels");
        return withId(company, 5L);
    }

    static Hub hub() {
        Hub hub = new Hub();
        hub.setName("Aveiro Centro");
        hub.setCapacity(10);
        return withId(hub, HUB_ID);
    }

    static Courier courier(Long id, Company company) {
        Courier courier = new Courier();
        courier.setName("Courier " + id);
        courier.setCompany(company);
        return withId(courier, id);
    }

    static Bike bike(Hub hub, BikeStatus status, int batteryLevel, boolean active) {
        Bike bike = new Bike();
        bike.setSerialNumber("ECO-0100");
        bike.setStatus(status);
        bike.setBatteryLevel(batteryLevel);
        bike.setActive(active);
        bike.setCurrentHub(hub);
        return withId(bike, BIKE_ID);
    }

    /** A reservation of {@code bike} by {@code courier}, from {@code plannedStart} for two hours. */
    static Reservation reservation(Courier courier, Bike bike, LocalDateTime plannedStart, ReservationStatus status) {
        Reservation reservation = new Reservation();
        reservation.setCourier(courier);
        reservation.setBike(bike);
        reservation.setStartHub(bike.getCurrentHub());
        reservation.setPlannedStart(plannedStart);
        reservation.setPlannedEnd(plannedStart.plusHours(2));
        reservation.setStatus(status);
        return withId(reservation, RESERVATION_ID);
    }

    static Payment deposit(PaymentStatus status) {
        Payment payment = new Payment();
        payment.setType(PaymentType.DEPOSIT);
        payment.setAmount(DEPOSIT);
        payment.setStatus(status);
        return payment;
    }

    static <T> T withId(T entity, Long id) {
        ReflectionTestUtils.setField(entity, "id", id);
        return entity;
    }
}
